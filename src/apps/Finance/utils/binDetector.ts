export function detectCardCompany(binString: string): string | null {
  // 1. 최소 6자리 이상 입력되었을 때만 처리
  if (!binString || binString.length < 6) return null;
  
  const bin6 = binString.substring(0, 6);
  const bin8 = binString.substring(0, 8); // 최근 8자리 BIN 도입 대비

  // 2. kr_bins.json에서 먼저 찾기 (6자리 또는 8자리)
  if (binDb[bin8]) return binDb[bin8];
  if (binDb[bin6]) return binDb[bin6];

  // 3. 찾지 못했다면 정규표현식(Fallback)으로 매칭
  for (const rule of fallbackRules) {
    if (rule.pattern.test(binString)) {
      return rule.name;
    }
  }

  return null;
}
